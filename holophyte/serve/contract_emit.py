import json
import re
import types
import typing
from pathlib import Path

DRAFT = "https://json-schema.org/draft/2020-12/schema"
KIND = "kind"
SCALARS = {str: "string", int: "integer", float: "number", bool: "boolean",
           type(None): "null"}
ZOD_SCALARS = {"string": "z.string()", "integer": "z.int()",
               "number": "z.number()", "boolean": "z.boolean()",
               "null": "z.null()"}
IDENTIFIER = re.compile(r"[A-Za-z_$][A-Za-z0-9_$]*")


class ContractError(ValueError):
    pass


def json_schema(body, description):
    defs = {}
    root = _schema(body, defs, body.__name__)
    return {"$schema": DRAFT, "title": body.__name__,
            "description": description, **root, "$defs": defs}


def _schema(annotation, defs, where):
    origin, args = typing.get_origin(annotation), typing.get_args(annotation)
    if annotation in SCALARS:
        return {"type": SCALARS[annotation]}
    if typing.is_typeddict(annotation):
        return _object(annotation, defs)
    if origin is typing.Literal:
        return ({"const": args[0]} if len(args) == 1
                else {"enum": list(args)})
    if origin is list and len(args) == 1:
        return {"type": "array", "items": _schema(args[0], defs, where)}
    if origin is dict and len(args) == 2 and args[0] is str:
        return {"type": "object",
                "additionalProperties": _schema(args[1], defs, where)}
    if origin in (typing.Union, types.UnionType):
        members = [_schema(arg, defs, where) for arg in args]
        return {"oneOf" if _kinded(args) else "anyOf": members}
    raise ContractError(f"{where}: {annotation!r} has no JSON Schema mapping")


def _kinded(members):
    return all(typing.is_typeddict(member) and typing.get_origin(
        typing.get_type_hints(member).get(KIND)) is typing.Literal
        for member in members)


def _object(body, defs):
    name = body.__name__
    hints = typing.get_type_hints(body, include_extras=True)
    properties = {key: _schema(_bare(hint), defs, f"{name}.{key}")
                  for key, hint in hints.items()}
    shape = {"type": "object", "properties": properties,
             "required": [key for key in hints
                          if key in body.__required_keys__],
             "additionalProperties": True}
    if defs.setdefault(name, shape) != shape:
        raise ContractError(f"$defs/{name} names two shapes")
    return {"$ref": f"#/$defs/{name}"}


def _bare(hint):
    while typing.get_origin(hint) in (typing.NotRequired, typing.Required):
        hint = typing.get_args(hint)[0]
    return hint


def render(routes, schema_dir, zod_file, command):
    schemas = {stem: json_schema(body, description)
               for stem, (body, description) in routes.items()}
    files = {schema_dir / f"{stem}.schema.json":
             json.dumps(schema, indent=2) + "\n"
             for stem, schema in schemas.items()}
    files[zod_file] = zod_module(schemas, command)
    return files


def write(root, files):
    for path, text in files.items():
        target = Path(root) / path
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.exists() or target.read_text("utf-8") != text:
            target.write_text(text, "utf-8")


def check(root, files, schema_dir):
    drift = [f"{path}: differs from a fresh render"
             for path, text in files.items()
             if not (Path(root) / path).is_file()
             or (Path(root) / path).read_text("utf-8") != text]
    found = sorted((Path(root) / schema_dir).glob("*"))
    drift += [f"{schema_dir / extra.name}: not a generated file"
              for extra in found if schema_dir / extra.name not in files]
    return drift


def zod_module(schemas, command):
    defs = {}
    for schema in schemas.values():
        for name, shape in schema["$defs"].items():
            if defs.setdefault(name, shape) != shape:
                raise ContractError(f"$defs/{name} names two shapes")
    lines = [f"// Generated by `{command}`; do not edit.",
             'import { z } from "zod";', ""]
    done = set()
    for name in defs:
        _emit(name, defs, done, lines)
    return "\n".join(lines)


def _emit(name, defs, done, lines):
    if name in done:
        return
    done.add(name)
    shape = defs[name]
    for ref in _refs(shape):
        _emit(ref, defs, done, lines)
    const = _const(name)
    fields = [f"  {_key(key)}: {_zod(value)}"
              + ("" if key in shape["required"] else ".optional()") + ","
              for key, value in shape["properties"].items()]
    lines += [f"export const {const} = z.looseObject({{", *fields, "});",
              f"export type {name} = z.infer<typeof {const}>;", ""]


def _refs(shape):
    if isinstance(shape, dict):
        if "$ref" in shape:
            yield shape["$ref"].rsplit("/", 1)[1]
        for value in shape.values():
            yield from _refs(value)
    elif isinstance(shape, list):
        for value in shape:
            yield from _refs(value)


def _const(name):
    return name[0].lower() + name[1:] + "Schema"


def _key(key):
    return key if IDENTIFIER.fullmatch(key) else json.dumps(key)


def _zod(shape):
    if "$ref" in shape:
        return _const(shape["$ref"].rsplit("/", 1)[1])
    if "const" in shape:
        return f"z.literal({json.dumps(shape['const'])})"
    if "enum" in shape:
        return f"z.enum({json.dumps(shape['enum'])})"
    if "oneOf" in shape:
        members = ", ".join(_zod(member) for member in shape["oneOf"])
        return f'z.discriminatedUnion("{KIND}", [{members}])'
    if "anyOf" in shape:
        return _union(shape["anyOf"])
    if shape.get("type") == "array":
        return f"z.array({_zod(shape['items'])})"
    if shape.get("type") == "object":
        return f"z.record(z.string(), {_zod(shape['additionalProperties'])})"
    return ZOD_SCALARS[shape["type"]]


def _union(members):
    rest = [member for member in members if member != {"type": "null"}]
    if len(rest) == 1:
        zod = _zod(rest[0])
    else:
        zod = f"z.union([{', '.join(_zod(member) for member in rest)}])"
    return zod + ".nullable()" if len(rest) < len(members) else zod
